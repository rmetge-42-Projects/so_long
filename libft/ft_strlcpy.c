#include <string.h>
#include "libft.h"

size_t	ft_strlcpy(char	*dest, const char	*src, size_t s)
{
	size_t	i;

	i = 0;
	if (s > 0)
	{
		while ((i < s -1) && (src[i]))
		{
			dest[i] = src[i];
			i++;
		}
		dest[i] = '\0';
	}
	while (src[i])
		i++;
	return (i);
}
